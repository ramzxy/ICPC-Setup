"""Lint/package the local chart and embed it for k3s's bundled Helm controller.

Usage: python3 deploy/package-domjudge.py [--helm /path/to/helm]
No cluster connection or third-party Python modules are needed.
"""

import argparse
import base64
from pathlib import Path
import re
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--helm", default="helm")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    chart = root / "deploy/charts/domjudge"
    output = (args.output or root / ".build/domjudge-release").resolve()
    output.mkdir(parents=True, exist_ok=True)
    subprocess.run([args.helm, "lint", str(chart), "--strict"], check=True)
    subprocess.run([args.helm, "package", str(chart), "--destination", str(output)], check=True)
    # Read the simple top-level version field in this repository's own Chart.yaml.
    version = re.search(r"^version:\s*(\S+)\s*$", (chart / "Chart.yaml").read_text(), re.M).group(1)
    package = output / f"domjudge-{version}.tgz"
    content = base64.b64encode(package.read_bytes()).decode("ascii")
    manifest = output / "domjudge-k3s.yaml"
    manifest.write_text(
        "# Generated by deploy/package-domjudge.py; contains no credentials.\n"
        "# Create namespace domjudge and Secret domjudge-database before applying.\n"
        "apiVersion: helm.cattle.io/v1\n"
        "kind: HelmChart\n"
        "metadata:\n"
        "  name: domjudge\n"
        "  namespace: kube-system\n"
        "spec:\n"
        "  targetNamespace: domjudge\n"
        "  createNamespace: true\n"
        "  timeout: 600s\n"
        "  failurePolicy: abort\n"
        f"  chartContent: {content}\n",
        encoding="utf-8",
    )
    print(f"k3s installer: {manifest}")


if __name__ == "__main__":
    main()
